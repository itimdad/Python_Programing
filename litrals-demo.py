#integer litrals
age = 20
student_id = 2

print(age)
print(student_id)

# floating litrals
price = 20.1
percentage = 77.0

print(price)
print(percentage)

# String Litrals
name = 'Imdad'
vill = "Gorakhpur"
mesg = """
    Imdad Firdausi from Gorakhpur
    Uttar Pradesh
    273306
"""
print(name)
print(vill)
print(mesg)

#Boolean Litrals
is_completed = True
is_empty = False
print(is_completed)
print(is_empty)

#None litrals
none = None
print(none)

#List Litrals  (mutable)
students = ["Imdad", "Ajay", "Vijay"]
print(students)

#Tuple Litrals (immutable)
courses = ("Java", "Python", "Ruby", "PHP")
print(courses)

#Set Litrals (duplicate not allowed, not follow insertion order)
cities = {"Pune", "Hyd", "Hyd", "Pune", "Chennai"}
print(cities)

#Dic Litrals (store data in key value pair)
student = {
    "name": "Imdad",
    "age": 20,
    "student_id": 2
}
print(student)